def test_xlsx_natural_order_cross_file_senses_and_empty_translations(tmp_path):
    write_book(tmp_path, [raw_row()], "10.xlsx")
    write_book(tmp_path, [raw_row()], "2.xlsx")
    (tmp_path / "~$2.xlsx").touch()
    snapshot = source.capture_dictionary(tmp_path)
    try:
        rows = list(snapshot.records())
        assert [(r["source_file"], r["sense_order"]) for r in rows] == [("2.xlsx", 1), ("10.xlsx", 2)]
        assert snapshot.missing["ja"] == 2 and snapshot.missing["en"] == 0
        assert snapshot.counts == {"2.xlsx": 1, "10.xlsx": 1}
        assert list(snapshot.records()) == rows
    finally:
        snapshot.close()


@pytest.mark.parametrize("case", ["header", "formula", "blank", "corrupt", "duplicate"])
def test_invalid_workbooks_rejected_before_database_access(tmp_path, case):
    if case == "header":
        write_book(tmp_path, headers=source.HEADERS[:-1])
    elif case == "formula":
        write_book(tmp_path, [raw_row(뜻풀이="=1+1")])
    elif case == "blank":
        write_book(tmp_path, [])
    elif case == "corrupt":
        (tmp_path / "1.xlsx").write_bytes(b"broken")
    else:
        write_book(tmp_path)
        (tmp_path / "1.xls").touch()
    with pytest.raises(TransferError):
        source.capture_dictionary(tmp_path)


def test_xls_reader_releases_workbook_and_preserves_numeric_homonym(monkeypatch, tmp_path):
    import xlrd

    path = tmp_path / "1.xls"
    path.touch()
    book, sheet = Mock(), Mock()
    book.nsheets = 1
    book.sheet_by_index.return_value = sheet
    sheet.nrows = 2
    row = raw_row(**{"동형어 번호": 1.0})
    sheet.row_values.side_effect = [source.HEADERS, [row[k] for k in source.HEADERS]]
    sheet.row_types.return_value = [xlrd.XL_CELL_TEXT] * len(source.HEADERS)
    monkeypatch.setattr(xlrd, "open_workbook", lambda *a, **kw: book)
    result = source.capture_dictionary(tmp_path)
    try:
        assert next(result.records())["homonym_number"] == 1
    finally:
        result.close()
    book.release_resources.assert_called_once()


def test_initial_import_noop_update_backup_and_id_preservation(snapshot, target, tmp_path):
    initial = send(snapshot, target, tmp_path)
    assert initial == {"status": "verified", "created": 2, "updated": 0, "unchanged": 0, "total": 2, "backup": None}
    before = stored(target)
    assert send(snapshot, target, tmp_path)["unchanged"] == 2
    assert stored(target) == before and not (tmp_path / "backups").exists()
    write_book(snapshot.directory, [raw_row(뜻풀이="바뀐 뜻"), raw_row(뜻풀이="소속되다.")])
    changed = source.capture_dictionary(snapshot.directory)
    try:
        result = send(changed, target, tmp_path)
    finally:
        changed.close()
    assert (result["updated"], result["unchanged"]) == (1, 1)
    after = stored(target)
    assert [r[0]["id"] for r in before] == [r[0]["id"] for r in after]
    assert after[0][0]["definition"] == "바뀐 뜻"
    with gzip.open(result["backup"], "rt", encoding="utf-8") as handle:
        header, *rows = [json.loads(line) for line in handle]
    assert header["format"] == "korean-dictionary-backup-v1"
    assert rows == [r[0] for r in before]
    with psycopg.connect(target) as c:
        assert c.execute("SELECT * FROM unrelated").fetchall() == [("preserve",)]


