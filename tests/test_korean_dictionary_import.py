def test_changed_file_is_rejected_even_if_stat_is_unchanged(snapshot, target, tmp_path):
    import os

    plan = importer.prepare_dictionary_import(snapshot, target)
    path = snapshot.directory / "1.xlsx"
    stat = path.stat()
    content = bytearray(path.read_bytes())
    content[-1] ^= 1
    path.write_bytes(content)
    os.utime(path, ns=(stat.st_atime_ns, stat.st_mtime_ns))
    with pytest.raises(TransferError, match="원본 파일이 변경"):
        importer.execute_dictionary_import(snapshot, target, plan, tmp_path)
    assert stored(target) == []


def test_failed_later_batch_rolls_back_and_sanitizes_errors(snapshot, target, tmp_path, monkeypatch):
    original = importer._write_batch
    calls = []

    def fail_second(c, records, existing):
        calls.append(True)
        if len(calls) == 2:
            raise RuntimeError("postgresql://user:synthetic-secret@host/db")
        original(c, records, existing)

    monkeypatch.setattr(importer, "BATCH_SIZE", 1)
    monkeypatch.setattr(importer, "_write_batch", fail_second)
    with pytest.raises(TransferError, match="커밋되지 않았습니다") as exc:
        send(snapshot, target, tmp_path)
    assert "synthetic-secret" not in str(exc.value)
    assert stored(target) == []


def test_backup_failure_blocks_updates(snapshot, target, tmp_path, monkeypatch):
    send(snapshot, target, tmp_path)
