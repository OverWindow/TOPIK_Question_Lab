def button(app, label):
    return next(b for b in app.button if b.label == label)


def test_ui_import_duplicate_targets_and_stale_selection(snapshot, target, monkeypatch):
    monkeypatch.setenv("QUESTION_BANK_LOCAL_DATABASE_URL", target)
    monkeypatch.setenv("QUESTION_BANK_PRODUCTION_DATABASE_URL", target)
    app = AppTest.from_file(str(PAGE), default_timeout=15).run()
    app.multiselect[0].set_value(["로컬 서버", "운영 서버"]).run()
