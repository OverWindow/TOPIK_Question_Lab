def default_topic_records() -> list[dict]:
    records: list[dict] = []
    index = 1
    short_reading_domains = {
        "생활·소비",
        "공공서비스·안전",
        "교육·학습",
        "직업·조직",
        "경제·산업",
        "건강·심리",
        "문화·예술",
        "지역사회·주거",
        "인간관계·소통",
    }
    narrative_domains = {
        "생활·소비",
        "교육·학습",
        "직업·조직",
        "건강·심리",
        "문화·예술",
        "지역사회·주거",
        "인간관계·소통",
    }
    conversational_listening_domains = {
        "생활·소비",
        "공공서비스·안전",
        "교육·학습",
        "직업·조직",
        "건강·심리",
        "문화·예술",
        "지역사회·주거",
        "인간관계·소통",
    }
    for domain, topics in TOPIC_SEED_GROUPS.items():
        reading_types = set(READING_GENERAL_TYPES)
        if domain in short_reading_domains:
            reading_types.update(READING_SHORT_TYPES)
        if domain in narrative_domains:
            reading_types.update(READING_NARRATIVE_TYPES)
        listening_types = (
            LISTENING_TOPIC_TYPES
            if domain in conversational_listening_domains
            else ACADEMIC_LISTENING_TYPES
        )
        for title, angles in topics:
            records.append(
                {
                    "id": f"topic_{index:03d}",
                    "domain": domain,
                    "title": title,
                    "angles": list(angles),
                    "reading_types": [type_id for type_id in READING_TYPES if type_id in reading_types],
                    "listening_types": list(listening_types),
                    "active": True,
                    "is_default": True,
                }
            )
            index += 1
    return records
