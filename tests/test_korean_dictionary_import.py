def raw_row(**overrides):
    return dict.fromkeys(source.HEADERS, "") | {
        "표제어": "가다", "동형어 번호": "1", "구분": "단어", "품사": "동사",
        "뜻풀이": "다른 곳으로 이동하다.", "용례": "<구> 학교에 가다.",
        "영어 대역어": "go", "영어 대역어 뜻풀이": "Move somewhere.",
    } | overrides


def write_book(directory, rows=None, name="1.xlsx", headers=None):
    directory.mkdir(parents=True, exist_ok=True)
    book = Workbook()
    sheet = book.active
    headers = source.HEADERS if headers is None else headers
    sheet.append(headers)
    for row in rows if rows is not None else [raw_row(), raw_row(뜻풀이="소속되다.")]:
        sheet.append([row[key] for key in headers])
    path = directory / name
    book.save(path)
    book.close()
    return path


