def test_mapping_languages_metadata_and_subentry_parent_identity():
    row = raw_row(발음="가다", **{"표제어": "  가다  ".strip()})
    for code, language in source.LANGUAGES.items():
        row[f"{language} 대역어"] = code
        row[f"{language} 대역어 뜻풀이"] = "definition-" + code
    orders = Counter()
    record = source.parse_row(row, "1.xls", 2, orders)
    assert record["headword"] == "가다"
    assert record["metadata"] == {"발음": "가다"}
    assert set(record["translations"]) == set(source.LANGUAGES)
    assert source.parse_row(row, "2.xls", 2, orders)["sense_order"] == 2
    subentry = raw_row(**{"표제어": "가난", "품사": "명사", "동형어 번호": "2", "구분": "부표제어",
                         "뜻풀이": "", "부표제어": "[속담] 가난이 죄다", "부표제어 뜻풀이": "뜻",
                         "부표제어 용례": "용례", "영어 부표제어 대역어": "Poverty"})
    sub = source.parse_row(subentry, "2.xls", 3, orders)
    assert (sub["headword"], sub["part_of_speech"], sub["homonym_number"], sub["entry_type"]) == ("가난이 죄다", "", 0, "proverb")
    assert sub["examples"] == "용례" and sub["translations"]["en"]["translation"] == "Poverty"
    assert sub["metadata"]["표제어"] == "가난" and sub["metadata"]["동형어 번호"] == "2"
    assert source.parse_row(subentry, "2.xls", 4, orders)["sense_order"] == 2
    assert source.parse_row(subentry | {"표제어": "다른 부모"}, "2.xls", 5, orders)["sense_order"] == 1


